"""The record hooks of banjo_d3d_records (step 4 of docs/d3d-full-replacement.md): one hook for every Direct3D
command-buffer writer that has no hook of its own, so that each outermost call's packets become host records.

   python tools/d3d/d3d_record_hooks.py           writes app/src/me/banjo_d3d_record_hooks.inc (included by
                                                  app/src/me/banjo_me_hooks.cpp), re-runs tools/post_codegen.py (the
                                                  callers of those functions then go through the hooks) and touches
                                                  banjo_me_hooks.cpp. Then build.
   python tools/d3d/d3d_record_hooks.py --list    prints the list only.

The list is the static scan of tools/d3d/d3d_writers.py (the functions that write after a device's write pointer or
call one of Direct3D's space functions), less the space functions themselves (a call that changes segment is left as
PM4 anyway) and less the functions that have a hook already (their hooks call the record functions themselves, or they
are helpers inside a hooked call). Unlike the census build (tools/d3d/d3d_census_build.py), this file IS part of the
normal build: a hook that is not reached at the outermost level of a call costs one counter test.
"""
import os, re, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
INC = os.path.join(ROOT, 'app', 'src', 'me', 'banjo_d3d_record_hooks.inc')
CENSUS_INC = os.path.join(ROOT, 'app', 'src', 'me', 'census', 'banjo_d3d_census_hooks.inc')
HOOKS_CPP = os.path.join(ROOT, 'app', 'src', 'me', 'banjo_me_hooks.cpp')
RENUT_GPU = os.path.join(ROOT, 'app', 'src', 'renut_engine', 'gpu')
# The writers Renut's renderer hooks too (written by tools/renut_gpu_import.py): their hooks call its side when
# banjo_renderer = "renut" (BANJO_D3D_RECORD_HOOK_SHARED, app/src/renut_engine/gpu/banjo_renut_select.h).
RENUT_SHARED = os.path.join(ROOT, 'app', 'src', 'me', 'banjo_renut_shared.txt')
# Direct3D's space functions (kick / next segment, "more space", inline data): not record writers.
SPACE = {'82210AB0', '821E2940', '8222D240'}
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))


def wanted_list():
    import d3d_writers
    funcs = d3d_writers.scan()
    wanted = {n[4:] for n in d3d_writers.writers(funcs) if re.fullmatch(r'sub_[0-9A-F]{8}', n)}
    defined = set()
    pattern = re.compile(r'(?:REX_HOOK_RAW\(sub_|REX_HOOK\(sub_|BANJO_HOT_HOOK\(sub_)([0-9A-F]{8})')
    for d in (os.path.join(ROOT, 'app', 'src'), os.path.join(ROOT, 'sdk', 'src'), os.path.join(ROOT, 'app', 'generated', 'hot')):
        for dp, _, fs in os.walk(d):
            for f in fs:
                path = os.path.join(dp, f)
                if not f.endswith(('.cpp', '.h', '.inc')):
                    continue
                if os.path.abspath(path) in (os.path.abspath(INC), os.path.abspath(CENSUS_INC)):
                    continue
                # Renut's renderer (tools/renut_gpu_import.py) hooks these writers for itself only: banjo-nx's renderer
                # still needs its record hooks there (BANJO_D3D_RECORD_HOOK_SHARED).
                if os.path.abspath(path).startswith(os.path.abspath(RENUT_GPU)):
                    continue
                defined |= set(pattern.findall(open(path, encoding='utf-8', errors='ignore').read()))
    return sorted(wanted - defined - SPACE), sorted(wanted & defined), sorted(wanted & SPACE)


def main():
    hooks, have, space = wanted_list()
    if '--list' in sys.argv:
        print('record hooks (%d):' % len(hooks), ' '.join(hooks))
        print('writers with a hook already (%d):' % len(have), ' '.join(have))
        print('space functions (%d):' % len(space), ' '.join(space))
        return
    with open(INC, 'w', newline='\n') as o:
        o.write('// Generated by tools/d3d/d3d_record_hooks.py: banjo_d3d_records\' hooks on Direct3D\'s command-buffer\n'
                '// writers that have no hook of their own (step 4 of docs/d3d-full-replacement.md). Do not edit.\n')
        shared = set(open(RENUT_SHARED).read().split()) if os.path.isfile(RENUT_SHARED) else set()
        for a in hooks:
            o.write(('BANJO_D3D_RECORD_HOOK_SHARED(%s)\n' if a in shared else 'BANJO_D3D_RECORD_HOOK(%s)\n') % a)
    os.utime(HOOKS_CPP, None)
    subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'post_codegen.py')], check=True, cwd=ROOT)
    print('%d record hooks written (%d writers have a hook already, %d space functions left out); now build'
          % (len(hooks), len(have), len(space)))


if __name__ == '__main__':
    main()
