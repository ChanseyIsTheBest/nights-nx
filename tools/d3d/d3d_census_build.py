"""The Direct3D census build (banjo_diag_d3d_census, app/src/me/banjo_d3d_census.h): hooks for every command-buffer
writer of Direct3D that has no hook of its own. From sa2-nx's tools/d3d/d3d_census_build.py (GPL-3.0); Banjo's
Direct3D is not one address range, so the list is the static scan of tools/d3d/d3d_writers.py plus the named entry
points of app/config/renut_gpu_funcs.toml.

   python tools/d3d/d3d_census_build.py            writes app/src/me/census/banjo_d3d_census_hooks.inc, re-runs
                                                   tools/post_codegen.py (the callers of those functions then go
                                                   through the hooks) and touches app/src/me/banjo_me_hooks.cpp, which
                                                   includes the file when it exists. Then build.
   python tools/d3d/d3d_census_build.py --restore  removes the file and re-runs the steps: the normal build again.

The hooks file is inside app/src on purpose: every post-codegen tool reads the addresses named there as hooked. It is
never part of a normal build or of a package. About half of the generated files are recompiled each way.
"""
import os, re, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
OUT = os.path.join(ROOT, 'app', 'src', 'me', 'census')
INC = os.path.join(OUT, 'banjo_d3d_census_hooks.inc')
HOOKS_CPP = os.path.join(ROOT, 'app', 'src', 'me', 'banjo_me_hooks.cpp')
SEGMENT = {'82210AB0', '821E2940'}  # Direct3D's space functions (kick / next segment, "more space")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))


def finish(message):
    os.utime(HOOKS_CPP, None)
    subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'post_codegen.py')], check=True, cwd=ROOT)
    print(message)


def main():
    if '--restore' in sys.argv:
        if os.path.isfile(INC):
            os.remove(INC)
        if os.path.isdir(OUT) and not os.listdir(OUT):
            os.rmdir(OUT)
        finish('census hooks removed: the normal build again (now build)')
        return
    import d3d_writers
    funcs = d3d_writers.scan()
    wanted = {n[4:] for n in d3d_writers.writers(funcs) if re.fullmatch(r'sub_[0-9A-F]{8}', n)}
    toml = open(os.path.join(ROOT, 'app', 'config', 'renut_gpu_funcs.toml'), encoding='utf-8').read()
    named = {m.upper() for m in re.findall(r'^0x([0-9A-Fa-f]{8})\s*=', toml, re.M)}
    wanted |= {a for a in named if 'sub_' + a in funcs}
    # Hooks that exist already (their code calls the census itself, or they are helpers below a counted call).
    defined = set()
    # (BANJO_D3D_RECORD_HOOK: banjo_d3d_records' hooks, which count for the census themselves.)
    pattern = re.compile(r'(?:REX_HOOK_RAW\(sub_|REX_HOOK\(sub_|BANJO_HOT_HOOK\(sub_|BANJO_D3D_RECORD_HOOK\()([0-9A-F]{8})')
    for d in (os.path.join(ROOT, 'app', 'src'), os.path.join(ROOT, 'sdk', 'src'), os.path.join(ROOT, 'app', 'generated', 'hot')):
        for dp, _, fs in os.walk(d):
            for f in fs:
                path = os.path.join(dp, f)
                if f.endswith(('.cpp', '.h', '.inc')) and os.path.abspath(path) != os.path.abspath(INC):
                    defined |= set(pattern.findall(open(path, encoding='utf-8', errors='ignore').read()))
    census = sorted(wanted - defined)
    os.makedirs(OUT, exist_ok=True)
    with open(INC, 'w', newline='\n') as o:
        o.write('// Generated by tools/d3d/d3d_census_build.py: the Direct3D census build\'s hooks (diagnostic only;\n'
                '// --restore removes this file). Not part of a normal build.\n')
        for a in census:
            o.write(('BANJO_D3D_CENSUS_SEGMENT_HOOK(%s)\n' if a in SEGMENT else 'BANJO_D3D_CENSUS_HOOK(%s)\n') % a)
    finish('%d functions wanted (%d writers by the scan, %d named), %d have a hook already, %d census hooks written '
           '(now build)' % (len(wanted), len(wanted - named), len(named & wanted), len(wanted & defined), len(census)))


if __name__ == '__main__':
    main()
