#!/usr/bin/env python3
"""nights-nx (2026-10-29): the bulk list of localized copies from a PC profile (tools/switch_hot_bulk.py's rules, for
the first round before a console profile exists; the user asked for the PC's sampling profiler first).

Input: app/out/pc-nx/logs/pc_profile.log (banjo_pc_profile_s = N; banjo_pc_profile_top = 200 or more), its gameplay
windows. Every guest function (renut!sub_XXXXXXXX, all game threads) is ranked by self samples; the first --top that
localize_native.py can copy become the list, leaving out (as switch_hot_bulk.py):
  - tiny leaves (at most --tiny guest instructions and no call: the generator inlines them already);
  - functions the copy tool refuses (localize_native.fits()), and the ones an app or SDK source mentions (hooks);
  - the functions of localized.txt and hand.txt (already natives).

  python -I tools/pc_hot_bulk.py [--log app/out/pc-nx/logs/pc_profile.log] [--from-report 4] [--top 100]
                                 [--write app/src/cpu/hot/localized_bulk.txt]
"""
import argparse
import collections
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
WINDOW = re.compile(r'^== pc profile window ([\d.]+) s')
THREAD = re.compile(r'^thread (\d+) "(.*)": busy ([\d.]+)% \((\d+) samples\)')
LINE = re.compile(r'^\s+[\d.]+%\s+renut!(sub_[0-9A-F]{8}) x(\d+)$')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--log', default=os.path.join(ROOT, 'app', 'out', 'pc-nx', 'logs', 'pc_profile.log'))
    ap.add_argument('--from-report', type=int, default=1)
    ap.add_argument('--top', type=int, default=100)
    ap.add_argument('--tiny', type=int, default=12)
    ap.add_argument('--write', default='')
    a = ap.parse_args()
    window, per_func = 0, collections.Counter()
    for line in open(a.log, encoding='utf-8', errors='replace'):
        if WINDOW.match(line):
            window += 1
            continue
        if window < a.from_report:
            continue
        m = LINE.match(line)
        if m:
            per_func[m.group(1)] += int(m.group(2))
    import localize_native as ln
    import store_cards
    index = ln.Index(ln.GEN)
    listed = [e[0] for e in ln.list_entries(ln.LIST)]
    hand = ln.hand_entries()
    hooks = ln.Hooks(listed)
    sizes = ln.addresses(ln.GEN)

    def raw_ok(sub):
        for _, l in index.body(sub):
            l = store_cards.restore_text(l)
            if 'REX_RAW_ADDR(' in l and not (ln.RAW_VECTOR_STORE.match(l) or ln.RAW_MEMSET.match(l) or
                                             ln.RAW_LOAD.match(l)):
                return False
        return True

    rows, left = [], collections.Counter()
    for sub, n in per_func.most_common():
        if len(rows) >= a.top:
            break
        f = index.funcs.get(sub)
        if f is None:
            why = 'not a generated function'
        elif sub in listed or sub in hand:
            why = 'already a native'
        elif not f['callees'] and not f['unknown'] and sizes.get(sub, (0, 4 * (a.tiny + 1)))[1] // 4 <= a.tiny:
            why = 'tiny leaf'
        elif hooks.replaced(sub):
            why = 'an app or SDK source mentions it'
        else:
            why = ln.fits(index, hooks, sub)
            if why == 'raw guest access' and raw_ok(sub):
                why = None
        if why:
            left[why.split(':')[0][:40]] += 1
            continue
        rows.append((sub, n, sizes.get(sub, (0, 0))[1] // 4, len(f['callees'])))
    total = sum(per_func.values())
    lines = ['# nights-nx: the bulk list of localized copies (tools/localize_native.py --bulk; hooks in the shard files',
             '# app/generated/hot/banjo_hot_bulk_<k>.inc). GENERATED by tools/pc_hot_bulk.py from the PC profile',
             f'# {os.path.relpath(a.log, ROOT)} (windows {a.from_report}..: Spring Valley gameplay), the first {a.top} guest',
             '# functions by self samples that the copy tool takes (tiny leaves, refused forms and hooked addresses left',
             '# out). The console decides: remake it from a console profile (tools/switch_hot_bulk.py) when one comes.',
             '# A line is "<address> <what>".', '']
    for sub, n, ins, calls in rows:
        lines.append(f'{sub[4:]} {n} PC samples ({100.0 * n / total:.2f} %), {ins} instructions, {calls} direct callees')
    print(f'{len(rows)} functions chosen of {len(per_func)} sampled; left out: ' +
          ', '.join(f'{k} {v}' for k, v in left.most_common()))
    print('\n'.join(lines[7:17]))
    if a.write:
        open(a.write, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
        print('written', a.write)


if __name__ == '__main__':
    main()
